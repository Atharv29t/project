package com.quizly.db;

import com.quizly.data.QuizCatalog;
import com.quizly.model.Question;
import com.quizly.model.Quiz;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

/**
 * Owns the embedded H2 database connection details and creates the schema.
 *
 * <p>The default database is a file next to the old CSV data:
 * <code>~/.quizly/quizly.mv.db</code>. Tests use an in-memory H2 URL. The
 * connection URL can be overridden with <code>-Dquizly.db.url</code> or the
 * <code>QUIZLY_DB_URL</code> environment variable.</p>
 */
public final class Database {

    private static final String DEFAULT_FILE_NAME = "quizly";

    private final String url;
    private final String username;
    private final String password;

    public Database(String url, String username, String password) {
        this.url = url;
        this.username = username == null ? "" : username;
        this.password = password == null ? "" : password;
    }

    public static Database appDatabase() {
        String configuredUrl = setting("quizly.db.url", "QUIZLY_DB_URL");
        String configuredUser = setting("quizly.db.user", "QUIZLY_DB_USER");
        String configuredPassword = setting("quizly.db.password", "QUIZLY_DB_PASSWORD");

        if (configuredUrl != null && !configuredUrl.isBlank()) {
            return new Database(configuredUrl, configuredUser, configuredPassword);
        }

        Path home = Path.of(System.getProperty("user.home"), ".quizly");
        try {
            Files.createDirectories(home);
        } catch (IOException exception) {
            throw new IllegalStateException("Could not create the Quizly data directory", exception);
        }

        String url = "jdbc:h2:file:" + home.resolve(DEFAULT_FILE_NAME).toAbsolutePath()
                + ";DB_CLOSE_ON_EXIT=FALSE";
        return new Database(url, configuredUser == null ? "sa" : configuredUser, configuredPassword);
    }

    public static Database inMemory(String name) {
        return new Database("jdbc:h2:mem:" + name + ";DB_CLOSE_DELAY=-1", "sa", "");
    }

    public void initialize() {
        try (Connection connection = openConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                        id VARCHAR(36) PRIMARY KEY,
                        name VARCHAR(80) NOT NULL,
                        email VARCHAR(190) NOT NULL UNIQUE,
                        password_hash VARCHAR(512) NOT NULL,
                        created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                        last_login_at TIMESTAMP WITH TIME ZONE
                    )
                    """);
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS quizzes (
                        id VARCHAR(64) PRIMARY KEY,
                        title VARCHAR(160) NOT NULL,
                        tagline VARCHAR(240) NOT NULL,
                        description VARCHAR(1200) NOT NULL,
                        icon VARCHAR(32) NOT NULL,
                        difficulty VARCHAR(32) NOT NULL,
                        estimated_minutes INT NOT NULL,
                        accent_color VARCHAR(16) NOT NULL,
                        sort_order INT NOT NULL
                    )
                    """);
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS questions (
                        id VARCHAR(64) PRIMARY KEY,
                        quiz_id VARCHAR(64) NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
                        prompt VARCHAR(1200) NOT NULL,
                        explanation VARCHAR(2400) NOT NULL,
                        sort_order INT NOT NULL
                    )
                    """);
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS question_options (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        question_id VARCHAR(64) NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
                        option_text VARCHAR(600) NOT NULL,
                        is_correct BOOLEAN NOT NULL,
                        sort_order INT NOT NULL
                    )
                    """);
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS results (
                        id VARCHAR(36) PRIMARY KEY,
                        user_id VARCHAR(36) REFERENCES users(id) ON DELETE SET NULL,
                        player_name VARCHAR(80) NOT NULL,
                        quiz_id VARCHAR(64) NOT NULL,
                        quiz_title VARCHAR(160) NOT NULL,
                        quiz_icon VARCHAR(32) NOT NULL,
                        accent_color VARCHAR(16) NOT NULL,
                        score INT NOT NULL,
                        total INT NOT NULL,
                        percentage INT NOT NULL,
                        completed_at TIMESTAMP WITH TIME ZONE NOT NULL
                    )
                    """);
            statement.execute("""
                    CREATE TABLE IF NOT EXISTS result_answers (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        result_id VARCHAR(36) NOT NULL REFERENCES results(id) ON DELETE CASCADE,
                        question_number INT NOT NULL,
                        prompt VARCHAR(1200) NOT NULL,
                        selected_answer VARCHAR(600),
                        correct_answer VARCHAR(600) NOT NULL,
                        explanation VARCHAR(2400) NOT NULL
                    )
                    """);
            statement.execute("CREATE INDEX IF NOT EXISTS idx_questions_quiz ON questions(quiz_id, sort_order)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_options_question ON question_options(question_id, sort_order)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_results_completed ON results(completed_at DESC)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_results_user ON results(user_id, completed_at DESC)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_answers_result ON result_answers(result_id, question_number)");
        } catch (SQLException exception) {
            throw new IllegalStateException("Could not initialise the Quizly database", exception);
        }

        seedQuizzes();
    }

    public Connection openConnection() throws SQLException {
        try {
            Class.forName("org.h2.Driver");
        } catch (ClassNotFoundException exception) {
            throw new SQLException("H2 JDBC driver is unavailable", exception);
        }
        return DriverManager.getConnection(url, username, password);
    }

    private void seedQuizzes() {
        try (Connection connection = openConnection()) {
            if (count(connection, "SELECT COUNT(*) FROM quizzes") > 0) {
                return;
            }

            connection.setAutoCommit(false);
            try {
                insertCatalogue(connection, QuizCatalog.all());
                connection.commit();
            } catch (SQLException exception) {
                connection.rollback();
                throw exception;
            } finally {
                connection.setAutoCommit(true);
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Could not seed the quiz catalogue", exception);
        }
    }

    private void insertCatalogue(Connection connection, List<Quiz> quizzes) throws SQLException {
        String insertQuiz = """
                INSERT INTO quizzes
                    (id, title, tagline, description, icon, difficulty, estimated_minutes, accent_color, sort_order)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """;
        String insertQuestion = """
                INSERT INTO questions (id, quiz_id, prompt, explanation, sort_order)
                VALUES (?, ?, ?, ?, ?)
                """;
        String insertOption = """
                INSERT INTO question_options (question_id, option_text, is_correct, sort_order)
                VALUES (?, ?, ?, ?)
                """;

        try (PreparedStatement quizStatement = connection.prepareStatement(insertQuiz);
             PreparedStatement questionStatement = connection.prepareStatement(insertQuestion);
             PreparedStatement optionStatement = connection.prepareStatement(insertOption)) {
            for (int quizIndex = 0; quizIndex < quizzes.size(); quizIndex++) {
                Quiz quiz = quizzes.get(quizIndex);
                quizStatement.setString(1, quiz.getId());
                quizStatement.setString(2, quiz.getTitle());
                quizStatement.setString(3, quiz.getTagline());
                quizStatement.setString(4, quiz.getDescription());
                quizStatement.setString(5, quiz.getIcon());
                quizStatement.setString(6, quiz.getLevel());
                quizStatement.setInt(7, quiz.getEstimatedMinutes());
                quizStatement.setString(8, quiz.getAccentColor());
                quizStatement.setInt(9, quizIndex);
                quizStatement.executeUpdate();

                for (int questionIndex = 0; questionIndex < quiz.getQuestions().size(); questionIndex++) {
                    Question question = quiz.getQuestions().get(questionIndex);
                    questionStatement.setString(1, question.getId());
                    questionStatement.setString(2, quiz.getId());
                    questionStatement.setString(3, question.getPrompt());
                    questionStatement.setString(4, question.getExplanation());
                    questionStatement.setInt(5, questionIndex);
                    questionStatement.executeUpdate();

                    for (int optionIndex = 0; optionIndex < question.getOptions().size(); optionIndex++) {
                        optionStatement.setString(1, question.getId());
                        optionStatement.setString(2, question.getOptions().get(optionIndex));
                        optionStatement.setBoolean(3, optionIndex == question.getCorrectOptionIndex());
                        optionStatement.setInt(4, optionIndex);
                        optionStatement.executeUpdate();
                    }
                }
            }
        }
    }

    private long count(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(sql)) {
            resultSet.next();
            return resultSet.getLong(1);
        }
    }

    private static String setting(String propertyName, String environmentName) {
        String value = System.getProperty(propertyName);
        if (value == null || value.isBlank()) {
            value = System.getenv(environmentName);
        }
        return value;
    }
}
